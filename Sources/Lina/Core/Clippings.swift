import AppKit
import Vision

/// What the writer gathered while researching: text they copied and screenshots they took, read with
/// on-device OCR. Off until the writer turns it on. Kept in memory only, so it's gone when Lina quits.
/// The palette's "Use what I gathered" writes with it.
@MainActor
final class Clippings: ObservableObject {
    struct Item: Identifiable, Equatable {
        enum Kind { case copied, screenshot }
        let id = UUID()
        let text: String
        let kind: Kind
        /// The app it was copied from, or "Screenshot".
        let source: String
        let date = Date()
    }

    static let shared = Clippings()
    static let limit = 30
    @Published private(set) var items: [Item] = []

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var screenshots: NSMetadataQuery?
    private let started = Date()

    /// Password managers and Lina's own pastes mark what they put on the clipboard; those are never kept.
    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    func setEnabled(_ on: Bool) {
        if on { start() } else { stop() }
    }

    private func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkPasteboard() }
        }
        watchScreenshots()
        Diagnostics.log("clippings", "gathering on")
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
        screenshots?.stop()
        screenshots = nil
        items.removeAll()
        Diagnostics.log("clippings", "gathering off")
    }

    func remove(_ id: Item.ID) { items.removeAll { $0.id == id } }
    func removeAll() { items.removeAll() }

    /// The newest clippings, as many as fit in a prompt.
    var promptText: String {
        var out: [String] = []
        var budget = 3500
        for item in items {
            let line = "- [\(item.source)] " + item.text.replacingOccurrences(of: "\n", with: " ")
            let clipped = line.count > 900 ? String(line.prefix(900)) + "…" : line
            guard clipped.count <= budget else { break }
            out.append(clipped)
            budget -= clipped.count
        }
        return out.joined(separator: "\n")
    }

    // MARK: Clipboard

    private func checkPasteboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = pb.types ?? []
        guard !types.contains(where: Self.skipTypes.contains) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        // Lina's own "Copy" from the palette or a report isn't research.
        guard front?.bundleIdentifier != Bundle.main.bundleIdentifier else { return }
        if let id = front?.bundleIdentifier, AppSettings.shared.disabledApps.contains(id) { return }
        let source = front?.localizedName ?? "Clipboard"

        if let text = pb.string(forType: .string) {
            add(text, kind: .copied, source: source)
        } else if let image = NSImage(pasteboard: pb), let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil) {
            // ⌃⇧⌘4 puts a screenshot straight on the clipboard.
            recognize(cg, source: source == "Screenshot" ? source : "Image from \(source)")
        }
    }

    private func add(_ text: String, kind: Item.Kind, source: String) {
        let clean = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard clean.count >= 3, !items.contains(where: { $0.text == clean }) else { return }
        items.insert(Item(text: String(clean.prefix(4000)), kind: kind, source: source), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    // MARK: Screenshots

    /// Spotlight marks screenshots saved to disk (⇧⌘3, ⇧⌘4, ⇧⌘5), wherever the writer keeps them.
    private func watchScreenshots() {
        let q = NSMetadataQuery()
        q.predicate = NSPredicate(format: "kMDItemIsScreenCapture == 1 AND kMDItemContentCreationDate > %@", started as NSDate)
        q.searchScopes = [NSMetadataQueryLocalComputerScope]
        NotificationCenter.default.addObserver(forName: .NSMetadataQueryDidUpdate, object: q, queue: .main) { [weak self] note in
            let added = (note.userInfo?[NSMetadataQueryUpdateAddedItemsKey] as? [NSMetadataItem]) ?? []
            let paths = added.compactMap { $0.value(forAttribute: NSMetadataItemPathKey) as? String }
            MainActor.assumeIsolated {
                for path in paths { self?.recognizeFile(URL(fileURLWithPath: path)) }
            }
        }
        q.start()
        screenshots = q
    }

    private func recognizeFile(_ url: URL) {
        guard let image = NSImage(contentsOf: url), let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil)
        else { return }
        recognize(cg, source: "Screenshot")
    }

    /// Reads the text in a picture with Apple's on-device Vision OCR.
    private func recognize(_ image: CGImage, source: String) {
        Task.detached(priority: .utility) {
            let request = VNRecognizeTextRequest()
            request.recognitionLevel = .accurate
            request.usesLanguageCorrection = true
            request.automaticallyDetectsLanguage = true
            try? VNImageRequestHandler(cgImage: image).perform([request])
            let text = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }.joined(separator: "\n")
            await MainActor.run { [weak self] in
                guard let self, self.timer != nil, !text.isEmpty else { return }
                self.add(text, kind: .screenshot, source: source)
                Diagnostics.log("clippings", "read \(text.count) chars from a screenshot")
            }
        }
    }
}
